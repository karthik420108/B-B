'use strict';

const config = require('../config');
const logger = require('../utils/logger');

/**
 * Cloud AI provider adapters (OpenAI / Anthropic).
 *
 * These are OPTIONAL and isolated behind the same interface as the local
 * provider. They are only used when:
 *   - AI_PROVIDER is set accordingly, AND
 *   - a valid API key is configured, AND
 *   - AI_ALLOW_EXTERNAL_DATA_TRANSFER=true (explicit disclosure/consent).
 *
 * When any of those is missing the provider reports `available: false` and the
 * service transparently falls back to the local provider. Document text is never
 * sent anywhere by default.
 *
 * Cost note (indicative, change over time): OpenAI/Anthropic charge per token;
 * a RAG answer sends only the retrieved excerpts (a few hundred tokens), not
 * whole documents. See the README for configuration.
 */

const SYSTEM_PROMPT = `You are a careful medical-records assistant embedded in a patient's personal health wallet.
You answer ONLY using the SOURCES provided. Rules:
- Never invent diagnoses, results, medications, dosages or dates.
- Cite the source of every factual claim using its [n] marker.
- If the sources do not contain the answer, say so explicitly and do not guess.
- Do not give treatment instructions or dosing advice.
- Be concise and use plain language.`;

function buildContext(sources) {
  return sources.map((s, i) => `[${i + 1}] (${s.kind}, ${s.date ? String(s.date).slice(0, 10) : 'date unknown'}, ${s.providerName || 'unknown provider'}) ${s.text}`).join('\n');
}

function mapCitations(sources) {
  return sources.map((s, i) => ({
    ref: i + 1,
    sourceId: s.id,
    kind: s.kind,
    recordId: s.recordId,
    label: s.label,
    date: s.date || null,
    providerName: s.providerName || null,
    documentId: s.documentId || null,
    documentName: s.documentName || null,
    verification: s.verification || null,
    origin: s.source || null,
  }));
}

async function callOpenAI({ system, user }) {
  const res = await fetch(`${config.ai.openai.baseUrl}/chat/completions`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${config.ai.openai.apiKey}` },
    body: JSON.stringify({
      model: config.ai.openai.model,
      temperature: 0.1,
      messages: [{ role: 'system', content: system }, { role: 'user', content: user }],
    }),
  });
  if (!res.ok) throw new Error(`OpenAI request failed (${res.status})`);
  const json = await res.json();
  return json.choices?.[0]?.message?.content?.trim() || '';
}

async function callAnthropic({ system, user }) {
  const res = await fetch(`${config.ai.anthropic.baseUrl}/v1/messages`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'x-api-key': config.ai.anthropic.apiKey,
      'anthropic-version': '2023-06-01',
    },
    body: JSON.stringify({
      model: config.ai.anthropic.model,
      max_tokens: 1024,
      system,
      messages: [{ role: 'user', content: user }],
    }),
  });
  if (!res.ok) throw new Error(`Anthropic request failed (${res.status})`);
  const json = await res.json();
  return (json.content || []).map((c) => c.text).join('\n').trim();
}

function makeCloudProvider(kind) {
  const isOpenAI = kind === 'openai';
  const key = isOpenAI ? config.ai.openai.apiKey : config.ai.anthropic.apiKey;
  const model = isOpenAI ? config.ai.openai.model : config.ai.anthropic.model;
  const available = Boolean(key) && config.ai.allowExternal;

  return {
    name: kind,
    model,
    available,
    reason: available ? undefined : (!key ? 'API key not configured.' : 'AI_ALLOW_EXTERNAL_DATA_TRANSFER is not true.'),
    async answer({ question, sources }) {
      const user = `SOURCES:\n${buildContext(sources)}\n\nQUESTION: ${question}\n\nAnswer using only the sources and cite them with [n]. If unknown, say so.`;
      const text = isOpenAI ? await callOpenAI({ system: SYSTEM_PROMPT, user }) : await callAnthropic({ system: SYSTEM_PROMPT, user });
      const cited = mapCitations(sources);
      return {
        answer: text,
        citations: cited,
        uncertainty: { level: 'medium', reason: 'Generated by an external model from the provided excerpts.', missing: false },
        provider: kind,
        model,
        usedSources: sources.length,
      };
    },
    async summarize({ records }) {
      const flat = [];
      for (const [kindName, arr] of Object.entries(records)) {
        for (const r of arr || []) flat.push({ ...r, kind: kindName });
      }
      const user = `SOURCES:\n${buildContext(flat)}\n\nProduce a structured medical summary with sections: conditions, allergies, current medications, historical medications, lab trends, visits, recent treatments, and missing/unverified information. Cite every fact with [n].`;
      const text = isOpenAI ? await callOpenAI({ system: SYSTEM_PROMPT, user }) : await callAnthropic({ system: SYSTEM_PROMPT, user });
      return {
        sections: { narrative: [{ text }] },
        narrative: text,
        missing: [],
        citations: mapCitations(flat),
        generatedAt: new Date().toISOString(),
        provider: kind,
        model,
        disclaimer: 'This is an automatically generated summary of stored records for reference and sharing. It is not a diagnosis and not verified medical advice.',
      };
    },
  };
}

module.exports = { makeCloudProvider };
